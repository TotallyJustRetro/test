#!/usr/bin/env python3
"""Draws the PipeClean logo.
   python3 tools/make_logo.py
   -> assets/pipeclean.png (256px), assets/pipeclean.ico (16..256), runtime/logo.c (64x64 RGBA)"""
import os, math
from PIL import Image, ImageDraw, ImageFilter, ImageChops

S = 1024
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")

def lerp(a, b, t): return tuple(int(a[i]+(b[i]-a[i])*t) for i in range(3))

def tile():
    img = Image.new("RGBA",(S,S),(0,0,0,0))
    top,bot = (9,24,52),(13,118,134)
    g = Image.new("RGBA",(S,S))
    gd = ImageDraw.Draw(g)
    for y in range(S): gd.line([(0,y),(S,y)], fill=lerp(top,bot,y/(S-1))+(255,))
    m = Image.new("L",(S,S),0)
    ImageDraw.Draw(m).rounded_rectangle([24,24,S-24,S-24],radius=210,fill=255)
    img.paste(g,(0,0),m)
    return img,m

def pipe_layer():
    body,light,dark,edge = (44,222,196),(176,255,242),(16,150,148),(8,70,84)
    vx0,vx1 = 250,470; hy0,hy1 = 520,740; top_y,right_x = 230,850; R = 120

    def sil(grow):
        g = grow
        m = Image.new("L",(S,S),0)
        d = ImageDraw.Draw(m)
        d.rectangle([vx0-g,top_y,vx1+g,hy1+g],fill=255)
        d.rectangle([vx0-g,hy0-g,right_x,hy1+g],fill=255)
        cx,cy = vx0-g+R, hy1+g-R
        cut = Image.new("L",(S,S),0)
        cd = ImageDraw.Draw(cut)
        cd.rectangle([vx0-g-1,cy,cx,hy1+g+1],fill=255)
        cd.ellipse([cx-R,cy-R,cx+R,cy+R],fill=0)
        return ImageChops.subtract(m,cut)

    L = Image.new("RGBA",(S,S),(0,0,0,0))
    L.paste(Image.new("RGBA",(S,S),edge+(255,)),(0,0),sil(14))
    L.paste(Image.new("RGBA",(S,S),body+(255,)),(0,0),sil(0))
    sh = Image.new("RGBA",(S,S),(0,0,0,0))
    d = ImageDraw.Draw(sh)
    d.rectangle([vx0+22,top_y+40,vx0+62,hy1-70],fill=light)
    d.rectangle([vx0+22,hy0+22,right_x-40,hy0+62],fill=light)
    d.rectangle([vx1-52,top_y+40,vx1-14,hy0+10],fill=dark)
    d.rectangle([vx0+100,hy1-50,right_x-40,hy1-14],fill=dark)
    d.pieslice([vx0+22,hy1-2*98-10,vx0+22+196,hy1-10],90,180,fill=dark)
    sh.putalpha(ImageChops.multiply(sh.getchannel("A"),sil(0)))
    L = Image.alpha_composite(L,sh)
    d = ImageDraw.Draw(L)
    for box in ([vx0-40,top_y-20,vx1+40,top_y+70],[right_x-10,hy0-40,right_x+80,hy1+40]):
        x0,y0,x1,y1 = box
        d.rounded_rectangle([x0-12,y0-12,x1+12,y1+12],radius=28,fill=edge)
        d.rounded_rectangle(box,radius=22,fill=body)
    d.rounded_rectangle([vx0-22,top_y-2,vx1+22,top_y+22],radius=10,fill=light)
    d.rounded_rectangle([right_x+6,hy0-22,right_x+30,hy1+22],radius=10,fill=light)
    for cx in (vx0-6,vx1+6): d.ellipse([cx-12,top_y+28,cx+12,top_y+52],fill=dark)
    for cy in (hy0-6,hy1+6): d.ellipse([right_x+44,cy-12,right_x+68,cy+12],fill=dark)
    return L

def star(cx,cy,r,rot=0):
    pts=[]
    for i in range(8):
        a=math.radians(45*i+rot-90); rr=r if i%2==0 else r*0.22
        pts.append((cx+rr*math.cos(a),cy+rr*math.sin(a)))
    return pts

def sparkle_layer():
    glow=Image.new("RGBA",(S,S),(0,0,0,0))
    ImageDraw.Draw(glow).polygon(star(690,360,250),fill=(150,255,240,200))
    glow=glow.filter(ImageFilter.GaussianBlur(26))
    sp=Image.new("RGBA",(S,S),(0,0,0,0))
    d=ImageDraw.Draw(sp)
    d.polygon(star(690,360,215),fill=(255,255,255,255))
    d.polygon(star(835,215,85),fill=(255,255,255,255))
    d.polygon(star(560,215,52),fill=(210,255,248,255))
    for (x,y,r) in ((820,420,20),(880,345,12)):
        d.ellipse([x-r,y-r,x+r,y+r],outline=(210,255,248,255),width=7)
    return Image.alpha_composite(glow,sp)

def build():
    img,mask = tile()
    sh=Image.new("RGBA",(S,S),(0,0,0,0))
    ImageDraw.Draw(sh).ellipse([-200,-520,S+200,380],fill=(255,255,255,26))
    sh.putalpha(Image.composite(sh.getchannel("A"),Image.new("L",(S,S),0),mask))
    img=Image.alpha_composite(img,sh)
    img=Image.alpha_composite(img,pipe_layer())
    img=Image.alpha_composite(img,sparkle_layer())
    return img

def c_array(im):
    px=im.tobytes()
    return "\n".join("    "+",".join("0x%02X"%b for b in px[i:i+16])+"," for i in range(0,len(px),16))

if __name__=="__main__":
    big=build()
    os.makedirs(os.path.join(root,"assets"),exist_ok=True)
    big.resize((256,256),Image.LANCZOS).save(os.path.join(root,"assets","pipeclean.png"))
    sizes=[16,24,32,48,64,128,256]
    big.resize((256,256),Image.LANCZOS).save(os.path.join(root,"assets","pipeclean.ico"),sizes=[(s,s) for s in sizes])
    small=big.resize((64,64),Image.LANCZOS)
    with open(os.path.join(root,"runtime","logo.c"),"w") as f:
        f.write("/* generated by tools/make_logo.py: 64x64 RGBA (R,G,B,A byte order) */\n#include \"logo.h\"\n")
        f.write("const unsigned char logo_rgba[LOGO_W * LOGO_H * 4] = {\n"+c_array(small)+"\n};\n")
    print("ok: pipeclean.png, pipeclean.ico, runtime/logo.c")
